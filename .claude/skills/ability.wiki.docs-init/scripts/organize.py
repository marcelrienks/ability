#!/usr/bin/env python3
"""Organize a project's documentation into wiki/ and wiki/raw/ (moves files in place).

Declared I/O exception: operates on the project in the current directory
(or --project DIR), not on data/. Prints an audit trail of every move.

  wiki/        markdown docs (folder structure preserved; socs/ flattened)
  wiki/raw/    static assets grouped by type
Root README.md stays in place. Folders emptied by the moves and empty orig/ and archive/ folders are removed.
"""
import argparse
import fnmatch
import os
import shutil
import sys
from pathlib import Path

EXCLUDED_DIRS = {"node_modules", "vendor", "venv", "addons", "plugins", "third_party", "external",
                 "lib", "libs", "dist", "build", "out", "wiki"}
EXCLUDED_SUBSTR = ("archive", "backup", "bak")
EXPORT_DIRS = {"exports", "clipped"}
CLEANUP_DIRS = {"docs", "orig", "archive"}
TXT_BLOCKLIST = ("requirements*.txt", "constraints*.txt", "cmakelists.txt", "license*.txt", "robots.txt")
STATIC_TYPES = {".pdf": "PDFs", ".docx": "Documents", ".doc": "Documents", ".xlsx": "Spreadsheets",
                ".xls": "Spreadsheets", ".pptx": "Presentations", ".ppt": "Presentations",
                ".vtt": "Transcripts", ".srt": "Transcripts", ".txt": "Notes"}


def excluded_dir(name: str, path: Path) -> bool:
    lower = name.lower()
    if name.startswith(".") or lower in EXCLUDED_DIRS or any(s in lower for s in EXCLUDED_SUBSTR):
        return True
    if lower == "specs":  # ignored only when generated by speckit (all subdirs start with spec-)
        subdirs = [d for d in path.iterdir() if d.is_dir()]
        return bool(subdirs) and all(d.name.startswith("spec-") for d in subdirs)
    return False


def classify(rel: Path):
    """Destination relative to the project root, or None to leave in place."""
    name, lower = rel.name, rel.name.lower()
    parts_lower = [p.lower() for p in rel.parts[:-1]]
    suffix = rel.suffix.lower()
    if lower == "readme.md" and len(rel.parts) == 1:
        return None
    if suffix == ".md":
        if EXPORT_DIRS & set(parts_lower):
            return Path("wiki/raw/Exports") / name
        if rel.parts[0].lower() == "socs":
            return Path("wiki") / name
        return Path("wiki") / rel
    if lower.endswith((".tar.gz", ".zip")):
        return Path("wiki/raw/Repos") / name if "repos" in parts_lower else None
    if suffix not in STATIC_TYPES:
        return None
    if suffix == ".txt" and any(fnmatch.fnmatch(lower, pat) for pat in TXT_BLOCKLIST):
        return None
    kind = STATIC_TYPES[suffix]
    if any(k in lower for k in ("transcript", "captions")) or "transcripts" in parts_lower:
        kind = "Transcripts"
    return Path("wiki/raw") / kind / name


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project", default=".", help="project root (default: current directory)")
    root = Path(parser.parse_args().project).resolve()
    (root / "wiki" / "raw").mkdir(parents=True, exist_ok=True)

    plan: list[tuple[Path, Path]] = []
    taken: set[Path] = set()
    for current, dirs, files in os.walk(root):
        current_path = Path(current)
        dirs[:] = sorted(d for d in dirs if not excluded_dir(d, current_path / d))
        for file in sorted(files):
            path = current_path / file
            rel = path.relative_to(root)
            dest = classify(rel)
            if dest is None:
                continue
            if dest in taken or (root / dest).exists():  # collision: path-qualified name
                dest = dest.with_name("-".join(rel.parts))
            taken.add(dest)
            plan.append((path, dest))

    for path, dest in plan:
        (root / dest).parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(path), str(root / dest))
        print(f"moved {path.relative_to(root)} -> {dest}")

    removed = []
    # folders emptied by the moves (and their emptied parents), plus empty orig/ and archive/
    candidates = {p.parent for p, _ in plan}
    candidates |= {Path(c) for c, _, _ in os.walk(root)
                   if Path(c).name.lower() in CLEANUP_DIRS and not Path(c).relative_to(root).parts[0].startswith(".")}
    for folder in sorted(candidates, key=lambda f: len(f.parts), reverse=True):
        while folder != root and folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
            removed.append(folder.relative_to(root))
            folder = folder.parent
    for folder in removed:
        print(f"removed empty {folder}/")
    print(f"organized {len(plan)} files, removed {len(removed)} empty folders in {root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
